-- Upcoming Meetings: paste into Supabase → SQL Editor → New query → Run (one time).
CREATE TABLE IF NOT EXISTS upcoming_meetings (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meeting_date  date NOT NULL,
  book          text,
  author        text,
  cover_url     text,
  location      text,
  created_at    timestamptz DEFAULT now()
);
ALTER TABLE upcoming_meetings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "allow_all_upcoming_meetings" ON upcoming_meetings;
CREATE POLICY "allow_all_upcoming_meetings" ON upcoming_meetings FOR ALL USING (true) WITH CHECK (true);
